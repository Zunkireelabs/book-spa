-- Per-tenant billing on/off switch, requested because Nuad Thai isn't using
-- invoices yet. Deliberately a per-org settings key, not a VITE_ENABLE_*
-- build-time flag (featureFlags.js) — this is one tenant opting out while
-- others opt in, and there are 2+ production tenants. Default false: nobody
-- should be able to hand a customer a tax invoice because a flag defaulted
-- on.
--
-- Enforced in issue_invoice() itself, not just hidden in the UI — the RPC is
-- callable by any authenticated session regardless of which buttons are
-- shown. Added to the SAME gate chain as legal name / PAN / tax mode, in the
-- SAME position AFTER the idempotent existing-invoice check — so disabling
-- billing blocks issuing NEW invoices but never blocks reprinting one that
-- already exists. A tenant that turns billing off still needs their past
-- invoices to stay reprintable for their own records.

